const filename = 'public/content/papers/n1-2010-07.json';
const paper = JSON.parse(readFileSync(filename,'utf8'));
const question = paper.sections[0].questions[0];
if (question.sentences.length !== lines.length) throw new Error('首题句子数量变化，需要重新审阅');
question.sentences.forEach((sentence:Record<string,unknown>, index:number) => {
  const [segmented,translation,highlightRole,grammar] = lines[index];
  const surfaces = segmented.split('|');
  if (surfaces.join('') !== sentence.text) throw new Error(`原文字面不匹配：${sentence.id}`);
  sentence.tokens = surfaces.map((surface,i) => {
    const id = `${sentence.id}-t${String(i+1).padStart(3,'0')}`;
    if (/^[。、！？\s]+$/.test(surface)) return {id,surface,isPunctuation:true};
    const data = vocabulary[surface];
    if (!data) throw new Error(`缺少释义：${surface}`);
    const [reading,meaning,pos,lemma,note] = data;
    return {id,surface,reading,meaning,pos,...(lemma ? {lemma}:{}),...(note ? {note}: {})};
  });
  sentence.translation = translation;sentence.grammarNotes = grammar ? [grammar] : [];
  sentence.highlightRole = highlightRole ?? 'neutral';
  sentence.tokensStatus = 'reviewed';
  sentence.annotationReview = 'agent_semantic_review; pending independent human review';
});
